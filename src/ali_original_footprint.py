"""Recover the original four-band positive-weight-center footprint exactly."""
import argparse,gzip,json,time
from pathlib import Path
import numpy as np
from astropy.io import fits


def run(args):
    out=args.out;out.mkdir(parents=True,exist_ok=True)
    meta=json.loads((args.coverage/'geometry.json').read_text())
    ny,nx=meta['native_shape_yx'];nb=(nx+7)//8;xmin,ymin=meta['global_origin_xy'];step=meta['step']
    bands=['F115W','F150W','F277W','F444W']
    for band in bands:
        if (out/(band+'.complete')).exists():continue
        bitmap=np.memmap(out/(band+'.bits'),dtype='uint8',mode='w+',shape=(ny,nb));bitmap[:]=0
        for rec in meta['inputs']:
            if rec['band']!=band:continue
            tile=rec['tile'];p=args.cache/tile/(band+'_wht_coverage.npz')
            sy,sx=rec['shape']
            if p.exists():
                with np.load(p) as z:packed=z['packed']
            else:
                print('Recover positive-weight centers',band,tile,flush=True)
                packed=np.empty((sy,(sx+7)//8),dtype='uint8')
                with gzip.open(rec['weight_path'],'rb') as f:
                    h=fits.Header.fromfile(f)
                    if h['BITPIX']!=-32:raise ValueError('Unexpected weight type')
                    for y in range(0,sy,128):
                        n=min(128,sy-y);raw=f.read(n*sx*4)
                        if len(raw)!=n*sx*4:raise IOError('Truncated WHT')
                        a=np.frombuffer(raw,'>f4').reshape(n,sx)
                        packed[y:y+n]=np.packbits(np.isfinite(a)&(a>0),axis=1)
                np.savez_compressed(p,packed=packed,shape_yx=[sy,sx])
            xo,yo=np.array(rec['global_offset_xy'])-[xmin,ymin];byte0,pad=divmod(int(xo),8)
            for y in range(0,sy,128):
                flag=np.unpackbits(packed[y:y+128],axis=1)[:,:sx]
                local=np.packbits(np.pad(flag,((0,0),(pad,0))),axis=1)
                bitmap[yo+y:yo+y+len(local),byte0:byte0+local.shape[1]]|=local
            bitmap.flush()
        (out/(band+'.complete')).write_text('complete\n');del bitmap
    maps=[np.memmap(out/(b+'.bits'),dtype='uint8',mode='r',shape=(ny,nb)) for b in bands]
    area=np.zeros((ny//step,nx//step));pixrad=np.deg2rad(.03/3600);xa=(np.arange(nx)+xmin)*pixrad
    for y in range(0,ny,step):
        joint=maps[0][y:y+step].copy()
        for m in maps[1:]:joint&=m[y:y+step]
        flag=np.unpackbits(joint,axis=1)[:,:nx];ya=(np.arange(y,y+step)+ymin)*pixrad
        jac=(1+ya[:,None]**2+xa[None,:]**2)**-1.5
        area[y//step]=(flag*jac).reshape(step,nx//step,step).sum(axis=(0,2))*pixrad**2
    np.savez_compressed(out/'original_four_area_map.npz',original_four_area_sr=area,global_origin_xy=[xmin,ymin],step=step)
    summary=dict(area_deg2=float(area.sum()*(180/np.pi)**2),definition='Intersection of four global native finite-positive-WHT unions; no aperture erosion; overlapping tiles counted once; TAN solid-angle Jacobian applied.')
    (out/'original_four_area.json').write_text(json.dumps(summary,indent=2)+'\n');print(summary,flush=True)


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--coverage',type=Path,default=Path('/home/bahareh/results/ali_native_coverage'))
    p.add_argument('--cache',type=Path,default=Path('/home/bahareh/results/ali_fiveband_reconstruction'))
    p.add_argument('--out',type=Path,default=Path('/home/bahareh/results/ali_original_coverage'))
    a=p.parse_args()
    # Run after the packed native masks have been generated by the main pass.
    while not (a.coverage/'F444W.complete').exists():time.sleep(15)
    run(a)
