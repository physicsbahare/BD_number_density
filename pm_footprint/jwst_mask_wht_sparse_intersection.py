"""Direct spatial JWST starmask ∩ local v13 F444W WHT>0 ∩ >=365d red epoch.

Uses the ALREADY supplied mask archive's weighted 0.6" Lambert samples
(generated by jwst_mask_union_repro), and read-only 4-byte os.pread per
point from local 50GB WHT. No large FITS array, new MAST query or 7GB
COSMOS-Web WHT download. Results are raster/MC geometric estimates,
NOT F444W=26.2 dropout selection or F356W PM completeness.
"""
import argparse
import json
import math
import os
from pathlib import Path

import numpy as np
import pandas as pd
from astropy.io import fits
from astropy.wcs import WCS
from shapely import STRtree, points

from .exact_geometry import CENTER_RA, CENTER_DEC, polygon_region, bands
from .jwst_mask_epoch_from_sample import epoch_flags


def lambert_inverse(x, y):
    """Inverse unit-sphere Lambert equal-area; x,y in radians."""
    x, y = np.asarray(x, float), np.asarray(y, float)
    if x.shape != y.shape:
        raise ValueError("Lambert coordinate shape mismatch")
    rho = np.hypot(x, y)
    if np.any(rho >= 2):
        raise ValueError("Outside Lambert projection")
    c = 2*np.arcsin(rho/2)
    s0, c0 = np.sin(np.deg2rad(CENTER_DEC)), np.cos(np.deg2rad(CENTER_DEC))
    dec = np.arcsin(np.clip(np.cos(c)*s0 +
        np.divide(y*np.sin(c)*c0, rho, out=np.zeros_like(rho), where=rho>0), -1, 1))
    ra = np.deg2rad(CENTER_RA) + np.arctan2(x*np.sin(c),
        rho*c0*np.cos(c) - y*s0*np.sin(c))
    return np.rad2deg(ra)%360, np.rad2deg(dec)


def sparse_wht_positive(path, ra, dec):
    """Native WHT pixel lookup; reads 4 bytes per in-bounds point."""
    path = Path(path)
    with path.open("rb") as f:
        h = fits.Header.fromfile(f, endcard=True, padding=True)
        offset = f.tell()
    if (h.get("NAXIS") != 2 or h.get("BITPIX") != -32
            or h.get("BSCALE", 1) != 1 or h.get("BZERO", 0) != 0):
        raise ValueError("Expected primary unscaled float32 WHT image")
    w = WCS(h).celestial
    if not w.has_celestial:
        raise ValueError("Missing celestial WCS")
    xx, yy = w.all_world2pix(ra, dec, 0)
    nx, ny = int(h["NAXIS1"]), int(h["NAXIS2"])
    valid_xy = np.isfinite(xx) & np.isfinite(yy)
    ix = np.rint(np.where(valid_xy, xx, -1)).astype(np.int64)
    iy = np.rint(np.where(valid_xy, yy, -1)).astype(np.int64)
    valid = valid_xy & (ix >= 0) & (iy >= 0) & (ix < nx) & (iy < ny)
    values = np.full(len(ix), np.nan)
    fd = os.open(path, os.O_RDONLY)
    try:
        for k in np.flatnonzero(valid):
            blob = os.pread(fd, 4, int(offset + 4*(iy[k]*nx + ix[k])))
            if len(blob) != 4:
                raise IOError("Truncated WHT pixel read")
            values[k] = np.frombuffer(blob, dtype=">f4")[0]
    finally:
        os.close(fd)
    positive = np.isfinite(values) & (values > 0)
    return positive, {
        "n_samples": len(ix),
        "n_inside_native_rectangle": int(valid.sum()),
        "n_WHT_positive": int(positive.sum()),
        "n_nonfinite_inside": int((valid & ~np.isfinite(values)).sum()),
        "bytes_of_native_WHT_pixels_read": int(valid.sum()*4),
        "WHT_file_size_bytes": path.stat().st_size
    }


def red_epoch_membership(x, y, metadata_csv, gap=365):
    """Exact CAOM polygon + disjoint observation-interval pair test."""
    raw = pd.read_csv(metadata_csv)
    f = raw.loc[
        raw.obs_collection.astype(str).str.upper().eq("JWST")
        & raw.instrument_name.astype(str).str.upper().eq("NIRCAM/IMAGE")
        & raw.dataproduct_type.astype(str).str.lower().eq("image")
        & raw.intentType.astype(str).str.lower().eq("science")
        & raw.dataRights.astype(str).str.upper().eq("PUBLIC")
        & raw.filters.astype(str).str.upper().str.contains("F277W|F356W|F410M|F444W")
    ].copy()
    f["t_min"] = pd.to_numeric(f.t_min, errors="coerce")
    f["t_max"] = pd.to_numeric(f.t_max, errors="coerce")
    f = f[np.isfinite(f.t_min) & np.isfinite(f.t_max)
          & (f.t_max >= f.t_min)].reset_index(drop=True)
    polygons = [polygon_region(s) for s in f.s_region]
    ii, jj = STRtree(polygons).query(points(x, y), predicate="intersects")
    matches = [[] for _ in range(len(x))]
    for i, j in zip(ii, jj):
        matches[int(i)].append(int(j))
    f444 = np.array(["F444W" in bands(v) for v in f.filters], bool)
    primary = f444 & f.proposal_id.astype(str).str.replace(
        r"\.0$", "", regex=True).eq("1727").to_numpy()
    starts, ends = f.t_min.to_numpy(float), f.t_max.to_numpy(float)
    archive = np.zeros(len(x), bool)
    red = np.zeros(len(x), bool)
    for k, indices in enumerate(matches):
        if not indices:
            continue
        ids = np.array(indices, dtype=int)
        archive[k], flags = epoch_flags(
            starts[ids], ends[ids], f444[ids], primary[ids], baselines=(gap,))
        red[k] = flags[gap]["red"]
    if np.any(red & ~archive):
        raise AssertionError("Red epoch outside archival F444W survey")
    return archive, red, {
        "n_public_red_imaging_rows": len(f),
        "n_mask_samples_in_archive": int(archive.sum()),
        "n_mask_samples_in_red_epoch": int(red.sum())
    }


def estimate(mask_area, archive, red, wht, wht_area, red_wht_area):
    """Joint MC estimate; analytic iid delta-method 95% halfwidths."""
    n = len(wht)
    if n < 100 or len(red) != n or len(archive) != n:
        raise ValueError("Need >=100 aligned mask samples")
    if np.any(red & ~archive):
        raise ValueError("Red must be nested in archive")
    if not 0 < red_wht_area < wht_area:
        raise ValueError("Invalid full WHT reference areas")
    a = np.asarray(wht, bool)
    b = a & np.asarray(red, bool)
    pa, pb = float(a.mean()), float(b.mean())
    x, y = mask_area*pa, mask_area*pb
    remaining_wht = wht_area-x
    remaining_red = red_wht_area-y
    if remaining_wht <= 0 or remaining_red < 0:
        raise ValueError("Mask exceeds WHT area")
    fraction = remaining_red/remaining_wht
    vx = mask_area**2*pa*(1-pa)/n
    vy = mask_area**2*pb*(1-pb)/n
    cov = mask_area**2*(pb-pa*pb)/n
    dx, dy = fraction/remaining_wht, -1/remaining_wht
    vf = max(0., dx*dx*vx + dy*dy*vy + 2*dx*dy*cov)
    return {
        "n_weighted_mask_samples": n,
        "n_mask_samples_in_archive": int(np.sum(archive)),
        "n_mask_samples_in_red": int(np.sum(red)),
        "n_mask_samples_in_WHT": int(a.sum()),
        "n_mask_samples_in_WHT_and_red": int(b.sum()),
        "mask_raster_upper_area_deg2": mask_area,
        "direct_mask_WHT_intersection_MC_deg2": x,
        "direct_mask_WHT_red365_intersection_MC_deg2": y,
        "direct_mask_WHT_nonred_intersection_MC_deg2": x-y,
        "corrected_WHT_positive_deg2": remaining_wht,
        "corrected_WHT_red365_deg2": remaining_red,
        "corrected_red_fraction": fraction,
        "MC_95pct_halfwidth_mask_WHT_deg2": 1.96*math.sqrt(vx),
        "MC_95pct_halfwidth_mask_WHT_red_deg2": 1.96*math.sqrt(vy),
        "MC_95pct_halfwidth_red_fraction": 1.96*math.sqrt(vf)
    }


def run(points_csv, mask_summary, wht_fits, metadata, output,
        wht_area=0.5336191141938245, red_wht_area=0.31740120807317784):
    sample = pd.read_csv(points_csv)
    if list(sample.columns) != ["x_lambert_rad", "y_lambert_rad"]:
        raise ValueError("Invalid weighted mask sample columns")
    x = sample.x_lambert_rad.to_numpy(float)
    y = sample.y_lambert_rad.to_numpy(float)
    ra, dec = lambert_inverse(x, y)
    wht, wht_qc = sparse_wht_positive(wht_fits, ra, dec)
    archive, red, epoch_qc = red_epoch_membership(x, y, metadata)
    mask = json.loads(Path(mask_summary).read_text())
    area = float(mask["grid_results"]["0.6"]["union_upper_bound_deg2"]
                 if "grid_results" in mask else
                 mask["grids"]["0.6arcsec"]["union_masked_area_approx_upper_deg2"])
    result = estimate(area, archive, red, wht, wht_area, red_wht_area)
    result.update({
        "status": "DIRECT_SPATIAL_JWST_MASK_V13_WHT_RED365_MC_NOT_SELECTION_COMPLETENESS",
        "reference_WHT_positive_deg2": wht_area,
        "reference_WHT_red365_deg2": red_wht_area,
        "native_WHT_sparse_read_QC": wht_qc,
        "epoch_polygon_QC": epoch_qc,
        "limitations": [
            "This is spatial WHT-mask-epoch overlap, but a 0.6arcsec raster weighted-cell-center Monte Carlo, NOT native 30mas exact mask union.",
            "WHT reference areas use a two-phase 3.6arcsec sample, not exact native-pixel area. Phase/raster systematics not in MC interval.",
            "Assumes code 1 is excluded, pending official documentation.",
            "WHT>0 is geometric coverage, not calibrated F444W=26.2 detection or blue-band dropout completeness.",
            "No F356W SNR/centroid precision, quality flags, crowding or source-level PM completeness.",
            "No new WHT download or large FITS data load."
        ]
    })
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, indent=2)+"\n")
    return result


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--points", required=True)
    p.add_argument("--mask-summary", required=True)
    p.add_argument("--wht", required=True)
    p.add_argument("--metadata", default="pm_footprint/results/mast_observations.csv")
    p.add_argument("--out", default="pm_footprint/results/jwst_starmask/direct_v13_wht_epoch_intersection.json")
    p.add_argument("--wht-area", type=float, default=0.5336191141938245)
    p.add_argument("--wht-red365-area", type=float, default=0.31740120807317784)
    a = p.parse_args()
    r = run(a.points, a.mask_summary, a.wht, a.metadata, a.out,
            a.wht_area, a.wht_red365_area)
    print(json.dumps({k:r[k] for k in (
        "direct_mask_WHT_intersection_MC_deg2",
        "direct_mask_WHT_red365_intersection_MC_deg2",
        "corrected_red_fraction",
        "MC_95pct_halfwidth_red_fraction")}, indent=2))


if __name__ == "__main__":
    main()
